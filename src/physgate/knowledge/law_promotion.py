"""``physgate knowledge promote-law`` and ``block-law``: a person moves a law into the gate's table.

The law table (``knowledge/laws/laws.toml``) holds the closed-form laws the physics gate judges
designs by. Like every curated file under ``knowledge/`` it is written only by a person at a
terminal, never by a session, and this module is that person's two steps:

- **promoting a staged law card.** A drafting agent stages a card at
  ``knowledge/staging/laws/<candidate_id>.toml`` (``candidate_id`` is 32 lowercase hexadecimal
  characters): the law's row, a page for the person, and the adversarial reviewer's verdict. The
  promotion writes the row into the table at ``status = "warn"``, its ``approved`` naming the
  candidate and the date, and appends one ``kind: "law"`` line to ``knowledge/promotions.jsonl``.
- **moving a law to ``block``.** The audit stages the law's clearance at
  ``knowledge/staging/laws/block/<law_id>.toml``. The move sets the row's status to ``block``
  with that clearance, dated the day the person approves it, and appends one
  ``kind: "law_status"`` line carrying the clearance.

The gate's loader holds every row to its line: a row whose approval names a candidate no
``law`` line promoted, or a ``block`` row whose clearance no ``law_status`` line records, stops
the gate from being built. So a row written any other way is refused where it matters.

**Both steps run** :func:`physgate.knowledge.promote.require_interactive` **first**, the same
guard every promotion has: they refuse unless standard input is a real terminal, before reading
anything. The write after it (:func:`_apply_law`, :func:`_apply_block`) carries no such check,
so it can be tested in a temporary library without a terminal; nothing calls it for a real
promotion but the two entries here, and the command is the one caller that matters. The guard is
not what keeps a session out of the table: the hooks are. They protect all of ``knowledge/``
but ``knowledge/staging/``, and put back a write that reaches it however it was made, this
module's own write step included.

**Nothing is written unless the result loads.** Before anything is written, the table with the
new row (or the moved one) and the record with the new line are loaded through the gate's own
loader, the law's worked examples run, in a temporary directory. A row that would not load, a
clearance under the block bar, a law already in the table or already at ``block``: each is
refused with the table, the record and the staged file left as they were.

The table is written whole, rows in id order, each row's keys in the order its card gave them,
under a fixed header. It is generated, never hand-edited, so nothing but its header comment, its
``[meta]`` and its rows is kept; a table that does not load as it stands is refused rather than
rewritten. The person is shown the row, its provenance and the table's sha256 before and after,
before the write.
"""

from __future__ import annotations

import datetime
import hashlib
import json
import math
import re
import tempfile
import time
import tomllib
from collections.abc import Callable, Mapping
from pathlib import Path
from typing import TYPE_CHECKING, Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field, StringConstraints, ValidationError

from physgate.knowledge.promote import (
    KNOWLEDGE_ROOT,
    PROMOTIONS_NAME,
    PromotionError,
    _append_record,
    _existing,
    _read_no_follow,
    _refuse_links,
    _replace,
    require_interactive,
)
from physgate.knowledge.staging import STAGING_ROOT

if TYPE_CHECKING:
    from physgate.gate.laws import Law

#: Where the table lives beneath the library, and where its cards and clearances are staged.
LAWS_NAME = "laws"
TABLE_NAME = "laws.toml"
BLOCK_NAME = "block"

#: The table's header: it is generated by promotion, so this is the one comment it keeps.
HEADER = """\
# The law table: closed-form laws the physics gate judges as its eighth check.
#
# Each law is one [[law]] row, promoted into this file by a person, never written by hand:
# drafted from the literature, reviewed adversarially, and approved, with a promotion line in
# knowledge/promotions.jsonl. Every law enters at status "warn"; it moves to "block" only by a
# person, after an audit over clean designs, with its clearance recorded on the row. The gate
# refuses to build on a row that does not load. The promotion command writes this file whole,
# rows in id order.
"""

#: Fields of a row that only a promotion or a move sets, never a card.
SET_BY_PROMOTION = ("status", "approved", "cleared")

_CANDIDATE_ID = re.compile(r"^[0-9a-f]{32}$")
_LAW_ID = re.compile(r"^[a-z][a-z0-9_]*$")
_BARE_KEY = re.compile(r"^[A-Za-z0-9_-]+$")

_Text = Annotated[str, StringConstraints(min_length=1, strip_whitespace=True)]


class _Strict(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid", strict=True)


class _CardMeta(_Strict):
    format: Literal[1]
    #: The pinned model string that drafted the card.
    drafted_by: _Text


class _Page(_Strict):
    #: What the person reads: what the law says, where it does not hold, its source, examples.
    text: _Text


class _Review(_Strict):
    #: The pinned model string that reviewed the card adversarially.
    by: _Text
    verdict: Literal["accept", "reject"]
    findings: _Text


class _Card(_Strict):
    card: _CardMeta
    law: dict[str, Any]
    page: _Page
    review: _Review


class _Clearance(_Strict):
    """The audit's clearance as staged: the person's date is added by the move."""

    audit_sha256: Annotated[str, StringConstraints(pattern=r"^[0-9a-f]{64}$")]
    evaluated_clean: Annotated[int, Field(ge=0)]
    designs: list[_Text]
    unexplained: Annotated[int, Field(ge=0)]


class _Staged(_Strict):
    cleared: _Clearance


def table_path(knowledge_root: Path = KNOWLEDGE_ROOT) -> Path:
    """The law table under ``knowledge_root``."""
    return Path(knowledge_root) / LAWS_NAME / TABLE_NAME


def card_path(candidate_id: str, staging_root: Path = STAGING_ROOT) -> Path:
    """Where the law card ``candidate_id`` is staged."""
    return Path(staging_root) / LAWS_NAME / f"{candidate_id}.toml"


def clearance_path(law_id: str, staging_root: Path = STAGING_ROOT) -> Path:
    """Where the clearance moving ``law_id`` to ``block`` is staged."""
    return Path(staging_root) / LAWS_NAME / BLOCK_NAME / f"{law_id}.toml"


# --- the two entries: a person at a terminal ------------------------------------------------


def promote_law(
    candidate_id: str,
    *,
    by: str,
    on: datetime.date | None = None,
    staging_root: Path = STAGING_ROOT,
    knowledge_root: Path = KNOWLEDGE_ROOT,
    promotions_path: Path | None = None,
) -> Path:
    """Refuse unless interactive, then promote one staged law card into the table at ``warn``.

    ``on`` is the approval's date, today's if not given.

    Raises:
        PromotionError: ``stdin`` is not a terminal, or the card cannot be promoted
            (:func:`_apply_law`).
    """
    require_interactive()
    return _apply_law(
        candidate_id,
        by=by,
        on=on,
        staging_root=staging_root,
        knowledge_root=knowledge_root,
        promotions_path=_record_path(knowledge_root, promotions_path),
        notice=print,
    )


def block_law(
    law_id: str,
    *,
    by: str,
    on: datetime.date | None = None,
    staging_root: Path = STAGING_ROOT,
    knowledge_root: Path = KNOWLEDGE_ROOT,
    promotions_path: Path | None = None,
) -> Path:
    """Refuse unless interactive, then move ``law_id`` to ``block`` with its staged clearance.

    ``on`` is the date of the person's approval of the move, today's if not given.

    Raises:
        PromotionError: ``stdin`` is not a terminal, or the law cannot be moved
            (:func:`_apply_block`).
    """
    require_interactive()
    return _apply_block(
        law_id,
        by=by,
        on=on,
        staging_root=staging_root,
        knowledge_root=knowledge_root,
        promotions_path=_record_path(knowledge_root, promotions_path),
        notice=print,
    )


def _record_path(knowledge_root: Path, promotions_path: Path | None) -> Path:
    if promotions_path is not None:
        return Path(promotions_path)
    return Path(knowledge_root) / PROMOTIONS_NAME


# --- the write after the terminal check ---------------------------------------------------


def _apply_law(
    candidate_id: str,
    *,
    by: str,
    on: datetime.date | None,
    staging_root: Path,
    knowledge_root: Path,
    promotions_path: Path,
    notice: Callable[[str], None] | None = None,
) -> Path:
    """Write a staged card's row into the table at ``warn``, record it, remove the card.

    Carries no terminal check of its own: :func:`promote_law` runs it first.

    Raises:
        PromotionError: ``by`` is empty; the id is not a plain candidate id; no card is staged
            under it, or it is a link; the card is not a card, carries what only promotion sets,
            was rejected by its reviewer or reviewed by the model that drafted it; the law is
            already in the table; or the table would not load with the row.
    """
    _named(by)
    if not _CANDIDATE_ID.fullmatch(candidate_id):
        msg = "a law card is named by a plain id: 32 lowercase hexadecimal characters"
        raise PromotionError(msg, candidate_id=candidate_id)
    staged = card_path(candidate_id, staging_root)
    card = _card(_staged_toml(staged, "no staged law card has this id"), staged)
    if card.review.verdict != "accept":
        msg = "its reviewer rejected the card: it goes back to drafting, not into the table"
        raise PromotionError(msg, candidate_id=candidate_id, reviewer=card.review.by)
    if card.review.by == card.card.drafted_by:
        msg = "its reviewer is the same model that drafted it, so the review is not adversarial"
        raise PromotionError(msg, candidate_id=candidate_id, model=card.review.by)
    carried = [field for field in SET_BY_PROMOTION if field in card.law]
    if carried:
        msg = f"the card's row carries {', '.join(carried)}, which only a promotion sets"
        raise PromotionError(msg, candidate_id=candidate_id)
    law_id = card.law.get("id")
    if not isinstance(law_id, str) or not law_id:
        msg = "the card's row names no law id"
        raise PromotionError(msg, candidate_id=candidate_id)
    table = _Table.read(knowledge_root, promotions_path)
    if law_id in table.ids():
        msg = f"law {law_id} is already in the table: a law is promoted once"
        raise PromotionError(msg, candidate_id=candidate_id, law=law_id)
    date = on if on is not None else datetime.date.today()
    row = {**card.law, "status": "warn", "approved": {"candidate_id": candidate_id, "date": date}}
    event: dict[str, object] = {
        "kind": "law",
        "law_id": law_id,
        "candidate_id": candidate_id,
    }

    def tell(law: Law, before: bytes, after: bytes) -> str:
        source = law.source
        return "\n".join(
            [
                f"promoting law card {candidate_id}: law {law_id} enters {table.path} at status "
                f"warn, approved {date.isoformat()} by {by}",
                f"  statement: {law.statement}",
                f"  expression: {law.expression}",
                f"  source: {source.kind} {source.title}, {source.edition}, {source.section} "
                f"(read {source.read.isoformat()}, {source.reading})",
                f"  drafted by {card.card.drafted_by}; reviewed by {card.review.by}, verdict "
                f"{card.review.verdict}: {card.review.findings}",
                f"  {table.path}: {_fingerprint(before)} -> {_fingerprint(after)}",
                "the row as written:",
                _row_text(row),
            ]
        )

    return table.commit(
        law_id, [*table.rows, row], event, tell, by=by, staged=staged, notice=notice
    )


def _apply_block(
    law_id: str,
    *,
    by: str,
    on: datetime.date | None,
    staging_root: Path,
    knowledge_root: Path,
    promotions_path: Path,
    notice: Callable[[str], None] | None = None,
) -> Path:
    """Move ``law_id`` to ``block`` with its staged clearance, record it, remove the clearance.

    Carries no terminal check of its own: :func:`block_law` runs it first.

    Raises:
        PromotionError: ``by`` is empty; the id is not a plain law id; no clearance is staged
            for it, or it is a link, or it is not a clearance, or it already carries the
            person's date; the law is not in the table or is already at ``block``; or the table
            would not load with the move (a clearance under the block bar).
    """
    _named(by)
    if not _LAW_ID.fullmatch(law_id):
        msg = "a law is named by a plain id: lowercase letters, digits and underscores"
        raise PromotionError(msg, law=law_id)
    staged = clearance_path(law_id, staging_root)
    raw = _staged_toml(staged, f"no staged clearance for law {law_id}")
    cleared = raw.get("cleared")
    if isinstance(cleared, Mapping) and "approved" in cleared:
        msg = "the clearance already carries the approval date (approved), which only a move sets"
        raise PromotionError(msg, law=law_id, path=str(staged))
    try:
        clearance = _Staged.model_validate(raw).cleared
    except ValidationError as exc:
        where, why = _refusal(exc)
        msg = f"the staged clearance does not hold a clearance: {where}: {why}"
        raise PromotionError(msg, law=law_id, path=str(staged)) from None
    table = _Table.read(knowledge_root, promotions_path)
    current = next((row for row in table.rows if row.get("id") == law_id), None)
    if current is None:
        msg = f"law {law_id} is not in the table"
        raise PromotionError(msg, law=law_id)
    if current.get("status") == "block":
        msg = f"law {law_id} is already at block"
        raise PromotionError(msg, law=law_id)
    date = on if on is not None else datetime.date.today()
    record: dict[str, Any] = {**clearance.model_dump(), "approved": date}
    moved = {**current, "status": "block", "cleared": record}
    rows = [moved if row is current else row for row in table.rows]
    event: dict[str, object] = {
        "kind": "law_status",
        "law_id": law_id,
        "status": "block",
        "audit_sha256": clearance.audit_sha256,
        "cleared": {**clearance.model_dump(), "approved": date.isoformat()},
    }

    def tell(law: Law, before: bytes, after: bytes) -> str:
        return "\n".join(
            [
                f"moving law {law_id} in {table.path} from warn to block, approved "
                f"{date.isoformat()} by {by}",
                f"  statement: {law.statement}",
                f"  audit: sha256 {clearance.audit_sha256}; {clearance.evaluated_clean} "
                f"evaluated instances on clean designs ({', '.join(clearance.designs)}), "
                f"{clearance.unexplained} unexplained",
                f"  {table.path}: {_fingerprint(before)} -> {_fingerprint(after)}",
            ]
        )

    return table.commit(law_id, rows, event, tell, by=by, staged=staged, notice=notice)


# --- reading what is staged and what is there ----------------------------------------------


def _named(by: str) -> None:
    if not by.strip():
        msg = "a law promotion needs the name of the person approving it"
        raise PromotionError(msg)


def _staged_toml(path: Path, missing: str) -> dict[str, Any]:
    """The staged file at ``path``, parsed, read without following a link.

    Raises:
        PromotionError: it is a link, it is not there, or it is not TOML.
    """
    if path.is_symlink():
        msg = "a staged law file is a link, so what it holds is somewhere else"
        raise PromotionError(msg, path=str(path))
    if not path.is_file():
        raise PromotionError(missing, path=str(path))
    try:
        return tomllib.loads(_read_no_follow(path).decode("utf-8"))
    except (tomllib.TOMLDecodeError, UnicodeDecodeError) as exc:
        msg = "the staged file is not TOML"
        raise PromotionError(msg, path=str(path), reason=str(exc)) from None


def _card(raw: dict[str, Any], path: Path) -> _Card:
    try:
        return _Card.model_validate(raw)
    except ValidationError as exc:
        where, why = _refusal(exc)
        msg = (
            "the staged card holds [card], [law], [page] and [review] as a card does: "
            f"{where}: {why}"
        )
        raise PromotionError(msg, path=str(path)) from None


def _refusal(exc: ValidationError) -> tuple[str, str]:
    first = exc.errors()[0]
    return ".".join(str(p) for p in first["loc"]) or "card", str(first["msg"])


def _fingerprint(data: bytes) -> str:
    return f"{len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()}"


class _Table:
    """The law table as it stands, and the one way it is rewritten: whole, and only if it loads."""

    def __init__(
        self, path: Path, knowledge_root: Path, promotions_path: Path, data: bytes
    ) -> None:
        self.path = path
        self.knowledge_root = Path(knowledge_root)
        self.promotions_path = promotions_path
        self.data = data
        parsed = tomllib.loads(data.decode("utf-8"))
        self.meta: dict[str, Any] = parsed["meta"]
        self.rows: list[dict[str, Any]] = list(parsed.get("law", []))

    @classmethod
    def read(cls, knowledge_root: Path, promotions_path: Path) -> _Table:
        """The table under ``knowledge_root``, refused unless it loads as it stands.

        Raises:
            PromotionError: the table, or a directory on its way, is a link; it is not there;
                or it does not load with the record as it stands.
        """
        path = table_path(knowledge_root)
        # Refused early and readably; what keeps the write safe is that it goes through
        # descriptors that do not follow a link, at the moment of writing.
        _refuse_links(path, Path(knowledge_root))
        data = _existing(path, Path(knowledge_root))
        if data is None:
            msg = "there is no law table to promote into"
            raise PromotionError(msg, path=str(path))
        _loads(data, _record(promotions_path), "the law table does not load as it stands")
        return cls(path, knowledge_root, promotions_path, data)

    def ids(self) -> set[str]:
        """Every law id the table holds."""
        return {str(row.get("id")) for row in self.rows}

    def commit(
        self,
        law_id: str,
        rows: list[dict[str, Any]],
        event: dict[str, object],
        tell: Callable[[Law, bytes, bytes], str],
        *,
        by: str,
        staged: Path,
        notice: Callable[[str], None] | None,
    ) -> Path:
        """Write ``rows`` and record ``event``, if the result loads; then remove ``staged``.

        Raises:
            PromotionError: the rows do not read back as written, or the table would not load
                with them and the new line.
        """
        ordered = sorted(rows, key=lambda row: str(row.get("id")))
        text = _table_text(self.meta, ordered)
        try:
            reads_back = tomllib.loads(text) == {"meta": self.meta, "law": ordered}
        except tomllib.TOMLDecodeError:
            reads_back = False
        if not reads_back:
            msg = "the table would not read back as it is written, so it is not written"
            raise PromotionError(msg, law=law_id)
        data = text.encode("utf-8")
        line = {
            **event,
            "destination": str(self.path),
            "promoted_by": by,
            "promoted": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            # The digest of the bytes written, which a later read of the path is held to.
            "sha256": hashlib.sha256(data).hexdigest(),
        }
        record = json.dumps(line, sort_keys=True) + "\n"
        loaded = _loads(
            data,
            _record(self.promotions_path) + record.encode("utf-8"),
            f"the table would not load with law {law_id}",
        )
        if notice is not None:
            notice(tell(loaded.laws[law_id], self.data, data))
        _replace(self.path, self.knowledge_root, data)
        _append_record(self.promotions_path, record)
        staged.unlink()
        return self.path


def _record(promotions_path: Path) -> bytes:
    path = Path(promotions_path)
    return path.read_bytes() if path.is_file() else b""


def _loads(table: bytes, record: bytes, refused: str) -> Any:
    """``table`` and ``record`` loaded through the gate's loader, in a temporary directory.

    Raises:
        PromotionError: the loader refuses them, its reason after ``refused``.
    """
    # Imported here: the gate brings its unit and algebra libraries, which only a promotion
    # needs, not every command that reads the knowledge layer.
    from physgate.gate.laws import LawTableError, load_laws

    with tempfile.TemporaryDirectory(prefix="law-promotion-") as scratch:
        table_file = Path(scratch) / TABLE_NAME
        record_file = Path(scratch) / PROMOTIONS_NAME
        table_file.write_bytes(table)
        record_file.write_bytes(record)
        try:
            return load_laws(table_file, record_file)
        except LawTableError as exc:
            msg = f"{refused}: {exc}"
            raise PromotionError(msg, **exc.context) from None


# --- writing the table -----------------------------------------------------------------------


def _table_text(meta: Mapping[str, Any], rows: list[dict[str, Any]]) -> str:
    """The whole table: the header, ``[meta]``, then each row under ``[[law]]``."""
    parts = [HEADER, "\n[meta]\n"]
    parts.extend(f"{_key(key)} = {_value(value)}\n" for key, value in meta.items())
    for row in rows:
        parts.append("\n" + _row_text(row))
    return "".join(parts)


def _row_text(row: Mapping[str, Any]) -> str:
    """One ``[[law]]`` row: a line per field, a list of tables one table per line."""
    lines = ["[[law]]"]
    lines.extend(f"{_key(key)} = {_value(value, top=True)}" for key, value in row.items())
    return "\n".join(lines) + "\n"


def _key(key: str) -> str:
    return key if _BARE_KEY.fullmatch(key) else _string(key)


def _string(text: str) -> str:
    """A TOML basic string: quotes, backslashes and control characters escaped, all else kept."""
    out = ['"']
    for char in text:
        code = ord(char)
        if char in '"\\':
            out.append("\\" + char)
        elif code < 0x20 or code == 0x7F:
            out.append(f"\\u{code:04x}")
        else:
            out.append(char)
    out.append('"')
    return "".join(out)


def _value(value: object, *, top: bool = False) -> str:
    """``value`` spelled as TOML. Only a row's own list of tables spans lines.

    Raises:
        PromotionError: a value TOML has no spelling for here (a time, or a number that is not
            finite).
    """
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            msg = "a row holds a number that is not finite"
            raise PromotionError(msg)
        return repr(value)
    if isinstance(value, str):
        return _string(value)
    if isinstance(value, datetime.datetime | datetime.time):
        msg = "a row holds a time of day, where a law's dates are dates"
        raise PromotionError(msg)
    if isinstance(value, datetime.date):
        return value.isoformat()
    if isinstance(value, list):
        if top and value and all(isinstance(item, dict) for item in value):
            return "[\n" + "".join(f"  {_value(item)},\n" for item in value) + "]"
        return "[" + ", ".join(_value(item) for item in value) + "]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        fields = ", ".join(f"{_key(str(k))} = {_value(v)}" for k, v in value.items())
        return "{ " + fields + " }"
    msg = f"a row holds a value TOML has no spelling for: {type(value).__name__}"
    raise PromotionError(msg)
